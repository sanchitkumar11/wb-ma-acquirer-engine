"""The Streamlit app runs from the cache alone: every page renders, in the agreed order, with no
key."""

from __future__ import annotations

from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
st_testing = pytest.importorskip("streamlit.testing.v1")
PAGES = [
    "summary",
    "bench",
    "how-we-built-the-list",
    "advocate-health",
    "nordic-capital",
    "sources",
]


def render(page: str, monkeypatch, target: str = "target_default.yaml"):
    monkeypatch.chdir(ROOT)
    monkeypatch.setenv("APP_START_PAGE", page)
    monkeypatch.setenv("APP_TARGET", target)
    at = st_testing.AppTest.from_file(str(ROOT / "app.py"), default_timeout=90)
    at.run()
    return at


@pytest.mark.parametrize("page", PAGES)
def test_every_page_renders(page, monkeypatch):
    at = render(page, monkeypatch)
    assert not at.exception
    assert any("Deal data through 2024 Q4" in c.value for c in at.caption)


def test_summary_is_the_one_pager(monkeypatch):
    """Page one holds the headline, summary, approach and call list, and none of the explanatory
    material."""
    at = render("summary", monkeypatch)
    headline = next(m.value for m in at.markdown if m.value.startswith("### "))
    assert "15.3x" in headline and not any(
        ch.isdigit() for ch in headline.replace("15.3x", "")
    )  # the multiple, no other numbers
    assert "sub-sector strategics" not in headline
    text = " ".join(m.value for m in at.markdown)
    assert "Executive summary" in text and "Recommended approach" in text and "who to call" in text
    assert (
        "Review log" not in text and "Sponsor scorecard" not in text and "Buyer motives" not in text
    )


def test_bench_and_appendix_hold_the_rest(monkeypatch):
    assert "Sponsor scorecard" in " ".join(m.value for m in render("bench", monkeypatch).markdown)
    assert "Review log" in " ".join(
        m.value for m in render("how-we-built-the-list", monkeypatch).markdown
    )


def test_new_target_without_cache_still_reports(monkeypatch):
    """A target never generated by the CLI: lists, scorecard and chart work; pages are marked
    missing."""
    from dataclasses import replace

    from acquirer_engine.charts import buyer_price_ranges
    from acquirer_engine.config import load_target
    from acquirer_engine.report import build
    from acquirer_engine.summary import review_log_rows, sponsor_scorecard, tier2_groups

    monkeypatch.chdir(ROOT)
    rep = build(
        replace(load_target(ROOT / "configs/target_default.yaml"), region="Southeast"), replay=True
    )
    assert rep.results is None and "not in the cache" in rep.missing
    assert (
        len(rep.tier1) == 10
        and tier2_groups(rep)
        and sponsor_scorecard(rep)
        and review_log_rows(rep)
    )
    rows, ask, note = buyer_price_ranges(rep, rep.tier1[0])
    assert ask == 200 and len(rows) >= 2 and "2024 Q4" in note


@pytest.mark.parametrize(
    "target,page",
    [
        ("target_healthit.yaml", "summary"),
        ("target_healthit.yaml", "evolent-health"),
        ("target_dental.yaml", "heartland-dental"),
        ("target_dental.yaml", "sources"),
    ],
)
def test_sample_targets_render_from_the_cache(target, page, monkeypatch):
    """Picking a sample target in the sidebar shows its own cached pages, with unresearched buyers
    marked."""
    at = render(page, monkeypatch, target)
    assert not at.exception and not any("not in the cache" in i.value for i in at.info)
    if page in ("heartland-dental", "sources"):  # Dental strategics have no profile yet
        assert any("not researched" in w.value.lower() for w in at.warning)
    if page == "evolent-health":  # profiled Oct 23 (EDGAR): no "not researched" warning
        assert not any("not researched" in w.value.lower() for w in at.warning)


def test_suggested_moves_panel_is_opt_in(monkeypatch, tmp_path):
    """Method page: the reviewer's moves appear only after the toggle, each with Accept and
    Reject."""
    monkeypatch.setenv("FEEDBACK_PATH", str(tmp_path / "f.jsonl"))
    at = render("how-we-built-the-list", monkeypatch)
    assert not any("Demote UPMC" in m.value for m in at.markdown)
    at.toggle(key="show-suggestions").set_value(True).run()
    assert not at.exception
    assert any("Demote UPMC" in m.value and "FOOTPRINT_OVERLAP" in m.value for m in at.markdown)
    assert any(b.label == "Accept" for b in at.button) and any(
        b.label == "Reject" for b in at.button
    )
